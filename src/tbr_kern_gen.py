"""Generate src/tbr_kern.py from src/majority_tail_kern.py by mechanical edits (queue 81).

The generated kernel kern_tbr is kern_mt with observational additions only (no random draws added or moved):
  - lastnew[i, s, k]: the last generation at which a copy of k arrived on island i, slot s, by migration (a migrant
    birth that changed the slot) or by a tail arrival that was applied; -1 if never (founders are not arrivals);
  - the final intro, arrf and t10 arrays are returned (presence-episode start, began-with-tail-arrival flag, first
    generation above N/2 in the current presence episode; 0 for a founder majority).
Run it once; tests/test_tbr.py checks that kern_tbr reproduces kern_mt draw for draw.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, 'majority_tail_kern.py')).read()


def sub(a, b, count=1):
    global src
    n = src.count(a)
    assert n == count, (a, n)
    src = src.replace(a, b)


sub('def kern_mt(', 'def kern_tbr(')
sub("    arrf = np.zeros((I, 3, K), np.int64)\n",
    "    arrf = np.zeros((I, 3, K), np.int64)\n    lastnew = np.full((I, 3, K), -1, np.int64)\n")
# tail arrivals (two call sites): record when applied
sub("            alog[na, 5] = ap; na += 1\n        ai += 1\n",
    "            alog[na, 5] = ap; na += 1\n        if ap == 1:\n            lastnew[i, s, arr_k[ai]] = 0\n        ai += 1\n")
sub("                    alog[na, 5] = ap; na += 1\n                ai += 1\n",
    "                    alog[na, 5] = ap; na += 1\n                if ap == 1:\n                    lastnew[i, s, arr_k[ai]] = g\n                ai += 1\n")
# migrant births that change the slot
sub("        counts[i, s, child] += 1; glob[s, child] += 1\n",
    "        counts[i, s, child] += 1; glob[s, child] += 1\n        if mig:\n            lastnew[i, s, child] = g + 1\n")
sub("    return (status, stop_gen, counts, modal, majo, snapc, snapd, xlog[:min(nx, xcap)], nx, alog[:min(na, acap)], na, nmig)",
    "    return (status, stop_gen, counts, modal, majo, snapc, snapd, xlog[:min(nx, xcap)], nx, alog[:min(na, acap)], na, nmig,\n"
    "            lastnew, intro, arrf, t10)")
hdr = ('"""GENERATED by src/tbr_kern_gen.py from src/majority_tail_kern.py (queue 81); do not edit by hand.\n\n'
       'kern_tbr = kern_mt plus observational records (lastnew; final intro, arrf, t10).  Original docstring follows.\n\n')
src = src.replace('"""', hdr, 1)
open(os.path.join(HERE, 'tbr_kern.py'), 'w').write(src)
print('wrote src/tbr_kern.py')
