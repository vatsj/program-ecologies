"""Generator of src/migration_window_kernels.py (migration-window experiment, notes/migration-window.md 1.1).

    python3 src/migration_window_gen.py

Copies stable_sets.kern and farsighted_refusal.fkern from their current source and inserts per-generation records of
each island's modal outcome, the encounter mass on efficient outcomes and on fair pairs.  No random draw is added,
moved or removed.  Every patched anchor is asserted to occur exactly the expected number of times, so a changed
source fails loudly instead of silently diverging."""
import inspect, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stable_sets as SS
import farsighted_refusal as F

HERE = os.path.dirname(os.path.abspath(__file__))


def patch(src, name, new_name):
    s = src.replace('def %s(' % name, 'def %s(' % new_name, 1)
    assert s != src

    def sub(old, new, count=1):
        nonlocal s
        assert s.count(old) == count, (old, s.count(old))
        s = s.replace(old, new)

    sub("    cls = np.zeros((H + 1, I), np.int16)\n",
        "    cls = np.zeros((H + 1, I), np.int16)\n"
        "    mw_modal = np.zeros((H + 1, I), np.int8); mw_effm = np.zeros((H + 1, I), np.float32)\n"
        "    mw_fairm = np.zeros((H + 1, I), np.float32)\n")
    if name == 'kern':
        cl = '_classify'
    else:
        cl = 'SS._classify'
    sub("        cls[0, i] = c\n", "        cls[0, i] = c\n        _rec(dist, nout, ISMEM, TOT, mw_modal, mw_effm, mw_fairm, 0, i)\n")
    sub("                cls[g, i] = c\n", "                cls[g, i] = c\n"
        "                _rec(dist, nout, ISMEM, TOT, mw_modal, mw_effm, mw_fairm, g, i)\n")
    sub("            cls[gg, i] = cls[stop_gen, i]\n",
        "            cls[gg, i] = cls[stop_gen, i]\n"
        "            mw_modal[gg, i] = mw_modal[stop_gen, i]; mw_effm[gg, i] = mw_effm[stop_gen, i]; mw_fairm[gg, i] = mw_fairm[stop_gen, i]\n")
    # the return statement (one occurrence; may span two lines)
    m = re.search(r"\n    return (.*?)\n\n\n", s + "\n\n\n", re.S)
    assert m
    ret = m.group(1)
    s = s.replace("\n    return " + ret, "\n    return " + ret.rstrip() + ", mw_modal, mw_effm, mw_fairm", 1)
    return s


HEADER = '''"""GENERATED by src/migration_window_gen.py from stable_sets.kern and farsighted_refusal.fkern -- do not edit.

kern_mw / fkern_mw are the originals with three added per-generation records (modal outcome, encounter mass on
efficient outcomes, encounter mass on fair pairs), appended to the original return tuples.  The random-number stream is
unchanged (tests/test_migration_window.py checks draw-for-draw identity with the originals)."""
import numpy as np
from numba import njit
import stable_sets as SS
import dominance_contracts as DC
from stable_sets import _fit_full, _setact, _classify, _parent, _closed, _code, _others
from farsighted_refusal import _gcounts, _ftypeid, reader_values, _consent


@njit(cache=True)
def _rec(dist, nout, ISMEM, TOT, modal, effm, fairm, g, i):
    mx = -1.0; arg = 0; ef = 0.0; fm = 0.0
    for z in range(nout):
        if dist[z] > mx:
            mx = dist[z]; arg = z
        if TOT[z] > 0.999:
            ef += dist[z]
        if ISMEM[z]:
            fm += dist[z]
    modal[g, i] = arg; effm[g, i] = ef; fairm[g, i] = fm


'''


def main():
    k = inspect.getsource(SS.kern.py_func)
    f = inspect.getsource(F.fkern.py_func)
    out = HEADER + patch(k, 'kern', 'kern_mw') + "\n\n" + patch(f, 'fkern', 'fkern_mw') + "\n"
    open(os.path.join(HERE, 'migration_window_kernels.py'), 'w').write(out)
    print('wrote', len(out.splitlines()), 'lines')


if __name__ == '__main__':
    main()
