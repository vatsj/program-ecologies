# ------------------------------------------------------------------ exact single-arrival sojourn
_SJ = {}


def sojourn(N, r):
    """(T, p_est): mean copy-generations of one arrival with constant relative fitness r in a Moran slot of N (N events
    per generation) until extinction or N/2 copies, and the probability of reaching N/2."""
    key = (N, round(float(r), 12))
    if key in _SJ:
        return _SJ[key]
    M = N // 2
    n = M - 1
    j = np.arange(1, M, dtype=float)
    tot = r * j + (N - j)
    up = r * j / tot * (N - j) / N
    dn = (N - j) / tot * j / N
    # expected events at each transient state from start 1 (tridiagonal solve)
    A = np.zeros((n, n))
    idx = np.arange(n)
    A[idx, idx] = up + dn
    A[idx[:-1], idx[:-1] + 1] = -up[:-1]
    A[idx[1:], idx[1:] - 1] = -dn[1:]
    e = np.zeros(n); e[0] = 1.0
    G = np.linalg.solve(A.T, e)
    T = float((G * j).sum() / N)
    pr = np.concatenate([[1.0], np.cumprod(dn / up)])
    pest = float(1.0 / pr.sum())
    _SJ[key] = (T, pest)
    return _SJ[key]


def fix_exact(N, r_var):
    """fixation from one copy at constant relative fitness r (Moran)."""
    if abs(r_var - 1.0) < 1e-14:
        return 1.0 / N
    return (1 - 1 / r_var) / (1 - r_var ** (-N))


# ------------------------------------------------------------------ arms
OTHERS = {0: (1, 2), 1: (0, 2), 2: (0, 1)}


class Tri:
    """Arm T or M: payoff tensor access over the full catalogue (global ids), seed law per slot."""

    def __init__(self, arm):
        import majority_tail as MT
        self.MT = MT
        self.arm = arm
        bl = MT.base_laws(arm)
        if arm == 'T':
            J, PAY, VEC, _, _ = MT.t_charged_tables(MT._tabs(), MT.PFAIL)
            self.J27, self.PAYt = J, PAY
            self.K = 27
            self.names = list(MT._tabs().names)
        else:
            import dollar3 as D
            self.D = D
            self.cat = MT.get_cat(arm)
            self.K = len(self.cat.S.fs)
            self.names = None
        self.seed = [renorm(np.asarray(b[:self.K], float)) for b in bl]
        names, fam = MT.family_table(arm)
        self.fam_names, self.fam = names, fam

    def pay(self, A0, A1, A2):
        A0 = np.asarray(A0, np.int64); A1 = np.asarray(A1, np.int64); A2 = np.asarray(A2, np.int64)
        if self.arm == 'T':
            return self.PAYt[self.J27[np.ix_(A0, A1, A2)]]
        S = self.cat.S
        codes = self.MT._joint16(self.cat.armi, S.nat, S.atL, S.atJ, S.atA, S.tab, self.D.PARTNER, A0, A1, A2)
        return self.MT.T.PAY[codes]

    def pay_slot(self, j, X, oth):
        """payoffs with slot j over X and the other slots over oth[o1], oth[o2]; axes (X, o1, o2, 3)."""
        o1, o2 = OTHERS[j]
        arr = [None] * 3
        arr[j] = X; arr[o1] = oth[o1]; arr[o2] = oth[o2]
        P = self.pay(*arr)
        if j == 0:
            return P
        if j == 1:
            return P.transpose(1, 0, 2, 3)
        return P.transpose(2, 0, 1, 3)

    def pname(self, s, k):
        if self.arm == 'T':
            return self.names[k]
        return 's%d:%d(%s)' % (s, k, self.fam_names[self.fam[s, k]])


def renorm(p):
    s = p.sum()
    return p / s if s > 0 else p


# ------------------------------------------------------------------ analysis of one world snapshot
def world_stats(G, N):
    I = G.shape[0]
    maj = G.argmax(2)
    share = G.max(2) / N
    prof = [tuple(int(x) for x in maj[i]) for i in range(I)]
    pc = Counter(prof)
    big = [p for p, c in pc.items() if c >= 0.05 * I]
    return maj, share, prof, pc, (len(big) >= 2)


def analyze(A, G, N, mN, founders, tail, lastnew=None, t10g=None, prior=True, comp=True, examples=True):
    """A: Tri; G: (I, 3, K) global counts.  Returns (world dict, list of case dicts)."""
    I = G.shape[0]
    K = A.K
    maj, share, prof, pc, diverse = world_stats(G, N)
    settled08 = share.min(1) >= 0.8
    settled095 = share.min(1) >= 0.95
    cnt = [Counter(maj[:, s].tolist()) for s in range(3)]
    ALL = np.arange(K)
    cache = {}
    cases = []
    tsup = [np.nonzero(tail[s] > 0)[0] for s in range(3)] if prior else None
    for i in range(I):
        p_prof = prof[i]
        t_res = None
        if t10g is not None:
            t_res = max(int(t10g[i, s, p_prof[s]]) for s in range(3))
        for j in range(3):
            o1, o2 = OTHERS[j]
            p = p_prof[j]; b = p_prof[o1]; c = p_prof[o2]
            key = (j, p, b, c)
            if key not in cache:
                cache[key] = _key_data(A, j, p, b, c, p_prof, cnt, N, mN, I, tail, tsup, prior, examples)
            kd = cache[key]
            E = kd['E']
            case = dict(i=i, j=j, p=int(p), smin=float(share[i].min()), set08=bool(settled08[i]), set095=bool(settled095[i]),
                        nat=kd['nat'], natpos=bool(kd['nat'] > TOL), nE=int(len(E)), vacE=bool(len(E) == 1),
                        vacA=kd['vacA'], vacT=kd['vacT'], regA=kd['regA_p'], regT=kd['regT_p'],
                        pmA=kd['pmA'], pmT=kd['pmT'])
            # founder control
            fw = founders[j][E].astype(float)
            if fw.sum() > 0:
                case['fdA'] = _ctl(fw, kd['regA']); case['fdT'] = _ctl(fw, kd['regT'])
            else:
                case['fdA'] = case['fdT'] = None
            # arrival control (horizon only)
            if lastnew is not None:
                mk = lastnew[i, j, E] >= t_res
                if mk.any():
                    case['arA'] = _ctl(mk.astype(float), kd['regA']); case['arT'] = _ctl(mk.astype(float), kd['regT'])
                else:
                    case['arA'] = case['arT'] = None
                case['t_res'] = t_res
            if prior:
                for k_ in ('prT_in', 'prA_in', 'prT_unc', 'prA_unc', 'pmprT', 'pmprA', 'vacPT', 'vacPA', 'threat'):
                    case[k_] = kd[k_]
            if examples and kd.get('ex') is not None:
                case['ex'] = kd['ex']
            if comp:
                case.update(_comp(A, G, i, j, p, N))
            cases.append(case)
    w = dict(diverse=bool(diverse), n_profiles=len(pc), big=[[list(k), v] for k, v in pc.most_common(6)],
             settled08=float(settled08.mean()), settled095=float(settled095.mean()))
    return w, cases, cache


def _ctl(wt, reg):
    s = wt.sum()
    return [float((wt * (reg <= TOL)).sum() / s), float((wt * reg).sum() / s)]


def _key_data(A, j, p, b, c, prof, cnt, N, mN, I, tail, tsup, prior, examples):
    K = A.K
    o1, o2 = OTHERS[j]
    nat = {o1: b, o2: c}
    row = A.pay_slot(j, np.arange(K), {o1: [b], o2: [c]})[:, 0, 0, :]
    E = np.nonzero(np.all(np.abs(row - row[p]) <= PTOL, axis=1))[0]
    ip = int(np.searchsorted(E, p))
    out = dict(E=E, nat=float(row[:, j].max() - row[p, j]))
    MP = np.zeros(len(E)); SG = np.zeros(len(E))
    contrib = []                                      # (s', q, weight*T*delta for the best variant) for examples
    per_slot = {}
    for sp in (o1, o2):
        spp = o2 if sp == o1 else o1
        Q = np.array(sorted(cnt[sp].keys()), np.int64)
        n_q = np.array([cnt[sp][q] - (1 if q == nat[sp] else 0) for q in Q], float)
        a_q = n_q / (I - 1)
        oth = {sp: Q, spp: [nat[spp]]}
        P = A.pay_slot(j, E, oth)                     # (|E|, ., ., 3)
        P = P[:, :, 0, :] if sp == o1 else P[:, 0, :, :]   # (|E|, |Q|, 3)
        uj = P[:, :, j]
        uq = P[ip, :, sp]                             # q's payoff in slot s' with p in slot j
        unat = row[p, sp]
        Tq = np.array([sojourn(N, math.exp(W * (u - unat)))[0] for u in uq])
        MP += 0.5 * (uj * a_q[None, :]).sum(1)
        d = uj - uj[ip][None, :]
        SG += W * (d * (mN * a_q * Tq)[None, :]).sum(1)
        per_slot[sp] = (Q, a_q, Tq, d)
    regA = MP.max() - MP; regT = SG.max() - SG
    out.update(regA=regA, regT=regT, regA_p=float(regA[ip]), regT_p=float(regT[ip]),
               vacA=bool(MP.max() - MP.min() <= TOL), vacT=bool(SG.max() - SG.min() <= TOL))
    pw = A.seed[j][E]
    out['pmA'] = _ctl(pw, regA) if pw.sum() > 0 else None
    out['pmT'] = _ctl(pw, regT) if pw.sum() > 0 else None
    out['ex'] = None
    if examples and regT[ip] > TOL:
        bv = int(np.argmax(SG))
        best = None
        for sp, (Q, a_q, Tq, d) in per_slot.items():
            v = W * mN * a_q * Tq * d[bv]
            k = int(np.argmax(v))
            if best is None or v[k] > best[0]:
                best = (float(v[k]), sp, int(Q[k]), float(d[bv, k]), float(a_q[k]), float(Tq[k]))
        out['ex'] = dict(kind='posreg', profile=list(prof), better=int(E[bv]), sigma=float(SG[bv]),
                         sep_slot=best[1], sep_migrant=best[2], delta=best[3], a_q=best[4], T_q=best[5])
    if prior:
        PPA = np.zeros(len(E)); PPT = np.zeros(len(E))
        threat = None
        for sp in (o1, o2):
            spp = o2 if sp == o1 else o1
            Q = tsup[sp]
            pi = tail[sp][Q]
            P = A.pay_slot(j, E, {sp: Q, spp: [nat[spp]]})
            P = P[:, :, 0, :] if sp == o1 else P[:, 0, :, :]
            uj = P[:, :, j]
            uq = P[:, :, sp]                          # q's payoff against each E member
            unat = row[p, sp]
            Tq = np.array([sojourn(N, math.exp(W * (u - unat)))[0] for u in uq[ip]])
            PPA += 0.5 * (uj * pi[None, :]).sum(1)
            d = uj - uj[ip][None, :]
            PPT += W * (d * (pi * Tq)[None, :]).sum(1)
            # costly threat carried by p: some p'' in E earns more against q while q earns more against p''
            if regT[ip] <= TOL:
                gain = d                               # p'' minus p, for p
                hurt = uq - uq[ip][None, :]            # q's payoff against p'' minus against p
                m = (gain > TOL) & (hurt > TOL)
                if m.any():
                    xs, qs = np.nonzero(m)
                    k = int(np.argmax(gain[xs, qs] * pi[qs]))
                    cand = (float(gain[xs[k], qs[k]] * pi[qs[k]]), sp, int(E[xs[k]]), int(Q[qs[k]]),
                            float(gain[xs[k], qs[k]]), float(hurt[xs[k], qs[k]]), float(pi[qs[k]]))
                    if threat is None or cand[0] > threat[0]:
                        threat = cand
        Astar = regT <= TOL
        out['prT_in'] = float(PPT[Astar].max() - PPT[ip]) if Astar[ip] else None
        AstarA = regA <= TOL
        out['prA_in'] = float(PPA[AstarA].max() - PPA[ip]) if AstarA[ip] else None
        out['prT_unc'] = float(PPT.max() - PPT[ip]); out['prA_unc'] = float(PPA.max() - PPA[ip])
        rT_in = PPT[Astar].max() - PPT; rA_in = PPA[AstarA].max() - PPA
        out['vacPT'] = bool(PPT[Astar].max() - PPT[Astar].min() <= TOL)
        out['vacPA'] = bool(PPA[AstarA].max() - PPA[AstarA].min() <= TOL)
        ws = A.seed[j][E] * Astar
        out['pmprT'] = _ctl(ws[Astar], rT_in[Astar]) if ws.sum() > 0 else None
        wsa = A.seed[j][E] * AstarA
        out['pmprA'] = _ctl(wsa[AstarA], rA_in[AstarA]) if wsa.sum() > 0 else None
        out['threat'] = None if threat is None else dict(slot=threat[1], variant=threat[2], tester=threat[3],
                                                          gain=threat[4], hurt=threat[5], pi=threat[6])
    return out


def _comp(A, G, i, j, p, N):
    o1, o2 = OTHERS[j]
    P1 = np.nonzero(G[i, o1])[0]; P2 = np.nonzero(G[i, o2])[0]
    x1 = G[i, o1, P1] / N; x2 = G[i, o2, P2] / N
    R = A.pay_slot(j, np.arange(A.K), {o1: P1, o2: P2})          # (K, n1, n2, 3)
    Ec = np.all(np.abs(R - R[p][None]) <= PTOL, axis=(1, 2, 3))
    ex = np.einsum('kab,a,b->k', R[..., j], x1, x2)
    return dict(nEc=int(Ec.sum()), natc=float(ex.max() - ex[p]))


# ------------------------------------------------------------------ routes
def routes(A, maj4, cases, cache, origin):
    """Route of each zero-T-regret, non-vacuous resident on a settled island at the horizon (exclusive, in order):
    c  the island's majority profile at 25% of the horizon has a different payoff vector (taken over; origin of the
       horizon holder's presence episode recorded: founder / migrant / tail);
    a  the 25% resident of the slot is a different member of E(p; k) with positive T-regret (replaced an on-path
       equivalent);
    b  the slot's majority was p at 25%, 50% and 75% (held);
    u  otherwise (a neutral swap within E, or replaced and returned).
    maj4: (I, 3) majority arrays at 25, 50, 75, 100%."""
    m25, m50, m75, m100 = maj4
    pv = {}

    def payvec(t, i):
        k = (t, i)
        if k not in pv:
            m = maj4[t][i]
            pv[k] = A.pay([m[0]], [m[1]], [m[2]])[0, 0, 0]
        return pv[k]
    out = []
    for cs in cases:
        if not (cs['set08'] and not cs['vacE'] and not cs['vacT'] and cs['regT'] <= TOL):
            continue
        i, j, p = cs['i'], cs['j'], cs['p']
        o1, o2 = OTHERS[j]
        kd = cache[(j, p, int(m100[i, o1]), int(m100[i, o2]))]
        org = origin.get((i, j, p), 'founder')
        p0 = int(m25[i, j])
        if np.max(np.abs(payvec(0, i) - payvec(3, i))) > PTOL:
            r = 'c'
        else:
            E = kd['E']
            x = int(np.searchsorted(E, p0))
            inE = x < len(E) and E[x] == p0
            if p0 != p and inE and kd['regT'][x] > TOL:
                r = 'a'
            elif p0 == p and int(m50[i, j]) == p and int(m75[i, j]) == p:
                r = 'b'
            else:
                r = 'u'
        out.append(dict(i=i, j=j, p=p, route=r, origin=org, natpos=cs['natpos']))
    return out
