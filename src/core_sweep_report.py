"""Summaries of runs/core-existence-sweep.json (tables for runs/core-existence-sweep.md and the notes)."""
import json
import os
import sys
from collections import Counter, defaultdict

import numpy as np

HERE = os.path.dirname(__file__)


def share(xs):
    xs = list(xs)
    return (sum(xs) / len(xs)) if xs else float('nan')


def vcount(recs, key=('tu', 'verdict')):
    c = Counter()
    for r in recs:
        x = r
        for k in key:
            x = x.get(k, {}) if isinstance(x, dict) else {}
        c[x if x else 'n/a'] += 1
    return c


def fmt_counts(c, order=('nonempty', 'tight', 'empty', 'unresolved', 'n/a')):
    return ' / '.join('%d' % c.get(k, 0) for k in order if c.get(k, 0) or k in ('nonempty', 'tight', 'empty'))


def row(*xs):
    return '| ' + ' | '.join(str(x) for x in xs) + ' |'


def by(recs, f):
    d = defaultdict(list)
    for r in recs:
        d[f(r)].append(r)
    return dict(sorted(d.items(), key=lambda kv: str(kv[0])))


def emp(r):
    return r['tu']['verdict'] == 'empty'


def report(res):
    L = []
    W = L.append
    W('# Core existence sweep: summary tables (generated by src/core_sweep_report.py)')
    W('')
    W('Verdict counts are nonempty / tight / empty (/ unresolved). "sim" = the simultaneous-partition (gamma) '
      'core. "FMA>0 in empty" = share of empty points with some coalition gaining from moving first. '
      '"dom" = follower dominance at every proper coalition.')
    # ---------------- Cournot
    if 'cournot' in res:
        W('')
        W('## Cournot (TU; p = 1 - Q, c1 = 0, others on the 0.025 grid to 0.5)')
        W(row('n', 'points', 'TU n/t/e', 'TU empty share', 'empty by singleton partition', 'sim n/t/e',
              'FMA>0 in empty', 'leader >= sim'))
        W(row(*['---'] * 8))
        for n, rs in by(res['cournot'], lambda r: r['n']).items():
            e = [r for r in rs if emp(r)]
            W(row(n, len(rs), fmt_counts(vcount(rs)), '%.3f' % share(emp(r) for r in rs),
                  '%d/%d' % (sum(1 for r in e if r.get('singleton_collection')), len(e)),
                  fmt_counts(vcount(rs, ('sim', 'verdict'))), '%.2f' % share(r['any_fma'] for r in e) if e else '-',
                  '%d/%d' % (sum(1 for r in rs if r.get('leader_ge_sim')), len(rs))))
        # ray onset
        W('')
        W('Ray c = (0, ..., 0, h): first empty h and last empty h on the grid')
        for n in (3, 4):
            hs = [r['params']['c'][-1] for r in res['cournot'] if r['n'] == n and all(x == 0 for x in r['params']['c'][:-1]) and emp(r)]
            W('- n = %d: empty at h in %s' % (n, sorted(hs)))
    if 'cournot_ntu' in res:
        W('')
        W('## Cournot NTU (0.05 subgrid) beside TU on the same points')
        W(row('n', 'points', 'TU n/t/e', 'NTU n/t/e/u', 'NTU empty share', 'TU empty share', 'NTU-empty by singleton bound'))
        W(row(*['---'] * 7))
        for n, rs in by(res['cournot_ntu'], lambda r: r['n']).items():
            nt = vcount(rs, ('ntu', 'verdict'))
            W(row(n, len(rs), fmt_counts(vcount(rs)), fmt_counts(nt), '%.3f' % share(r['ntu']['verdict'] == 'empty' for r in rs),
                  '%.3f' % share(emp(r) for r in rs),
                  sum(1 for r in rs if r['ntu']['verdict'] == 'empty' and r['singleton_bound'])))
        W('')
        W('n = 2 NTU verdict by c2: ' + ', '.join('%.2f:%s' % (r['params']['c'][1], r['ntu']['verdict'][0])
                                                 for r in res['cournot_ntu'] if r['n'] == 2))
        nonemp = [(r['params']['c'], r['ntu']['verdict']) for r in res['cournot_ntu'] if r['n'] > 2 and r['ntu']['verdict'] != 'empty']
        W('')
        W('n >= 3 NTU points not empty: %s' % nonemp)
    if 'cournot_cap' in res:
        W('')
        W('## Cournot with a common capacity k (TU; costs on the 0.1 grid)')
        W(row('n', 'k', 'points', 'TU n/t/e', 'empty share', 'sim n/t/e'))
        W(row(*['---'] * 6))
        for (n, k), rs in by(res['cournot_cap'], lambda r: (r['n'], r['params']['k'][0])).items():
            W(row(n, k, len(rs), fmt_counts(vcount(rs)), '%.3f' % share(emp(r) for r in rs), fmt_counts(vcount(rs, ('sim', 'verdict')))))
    if 'hombertrand' in res:
        W('')
        W('## Homogeneous Bertrand')
        W(row('n', 'points', 'TU n/t/e', 'NTU n/t/e', 'points with an unattained leader value'))
        W(row(*['---'] * 5))
        for n, rs in by(res['hombertrand'], lambda r: r['n']).items():
            W(row(n, len(rs), fmt_counts(vcount(rs)), fmt_counts(vcount(rs, ('ntu', 'verdict'))),
                  sum(1 for r in rs if r['unattained'])))
    if 'pg' in res:
        W('')
        W('## Public goods (u = theta f(G) - g)')
        W(row('f', 'n', 'points', 'TU n/t/e', 'TU empty share', 'NTU n/t/e/u', 'sim n/t/e', 'empty with free-rider in collection',
              'empty by singletons', 'FMA>0 in empty'))
        W(row(*['---'] * 10))
        for (f, n), rs in by(res['pg'], lambda r: (r['params']['f'], r['n'])).items():
            e = [r for r in rs if emp(r)]
            W(row(f, n, len(rs), fmt_counts(vcount(rs)), '%.3f' % share(emp(r) for r in rs),
                  fmt_counts(vcount(rs, ('ntu', 'verdict'))), fmt_counts(vcount(rs, ('sim', 'verdict'))),
                  '%d/%d' % (sum(1 for r in e if r.get('collection_has_free_rider')), len(e)),
                  '%d/%d' % (sum(1 for r in e if r.get('singleton_collection')), len(e)),
                  '%.2f' % share(r['any_fma'] for r in e) if e else '-'))
        W('')
        W('Symmetric public-goods points (theta equal): TU verdict')
        for (f, n), rs in by([r for r in res['pg'] if len(set(r['params']['theta'])) == 1],
                             lambda r: (r['params']['f'], r['n'])).items():
            W('- %s n=%d: %s' % (f, n, ', '.join('%g:%s' % (r['params']['theta'][0], r['tu']['verdict'][0]) for r in rs)))
        W('')
        W('Empty log points at n = 3: %s' % [r['params']['theta'] for r in res['pg'] if r['params']['f'] == 'log' and r['n'] == 3 and emp(r)])
    if 'lq' in res:
        W('')
        W('## Linear-quadratic supermodular games (u = b x - x^2/2 + gamma x X_-i + sigma X_-i)')
        W(row('spillover', 'n', 'points', 'TU n/t/e', 'NTU n/t/e/u', 'sim n/t/e', 'dom at all S', 'FMA>0 any', 'symmetric pts n/t/e'))
        W(row(*['---'] * 9))
        for (sc, n), rs in by(res['lq'], lambda r: (r['spill_class'], r['n'])).items():
            sy = [r for r in rs if r['symmetric']]
            W(row(sc, n, len(rs), fmt_counts(vcount(rs)), fmt_counts(vcount(rs, ('ntu', 'verdict'))),
                  fmt_counts(vcount(rs, ('sim', 'verdict'))), '%.3f' % share(r['all_dominance'] for r in rs),
                  '%.3f' % share(r['any_fma'] for r in rs), fmt_counts(vcount(sy))))
        fl = Counter(f for r in res['lq'] for f in r.get('flags', []))
        W('')
        W('Flags: %s' % dict(fl))
        W('')
        W('By sigma (TU empty share, all n): ' + ', '.join('%g: %.3f' % (s, share(emp(r) for r in rs))
                                                         for s, rs in by(res['lq'], lambda r: r['params']['sigma']).items()))
    if 'bertrand' in res:
        W('')
        W('## Differentiated Bertrand (q_i = 1 - p_i + g/(n-1) sum p_j)')
        W(row('n', 'g', 'points', 'excluded', 'TU n/t/e', 'NTU n/t/e/u', 'sim n/t/e', 'dom at all S', 'symmetric: any FMA>0'))
        W(row(*['---'] * 9))
        for (n, g), rs in by(res['bertrand'], lambda r: (r['n'], r['params']['g'])).items():
            inc = [r for r in rs if not r['excluded']]
            sy = [r for r in inc if r['symmetric']]
            W(row(n, g, len(rs), len(rs) - len(inc), fmt_counts(vcount(inc)), fmt_counts(vcount(inc, ('ntu', 'verdict'))),
                  fmt_counts(vcount(inc, ('sim', 'verdict'))), '%.3f' % share(r['all_dominance'] for r in inc),
                  any(r['any_fma'] for r in sy)))
    if 'exchange' in res:
        W('')
        W('## Allocation games (exchange economies; 50 random instances per cell)')
        W('TU verdicts are certified with primal (lower) and dual (upper) coalition values: nonempty with upper values '
          'for proper coalitions and the lower grand value, empty with the reverse.')
        W(row('utility', 'variant', 'sel', 'n', 'm', 'TU certified n/e/u', 'NTU n/t/e/u', 'NTU method'))
        W(row(*['---'] * 8))
        key = lambda r: (r['params']['util'] + ('' if r['params'].get('r') is None else '(r=%g)' % r['params']['r']),
                         r['params']['variant'], r['sel'], r['n'], len(r['params']['alpha'][0]))
        for k, rs in by(res['exchange'], key).items():
            tc = Counter(r.get('tu_certified', r['tu']['verdict']) for r in rs)
            W(row(*k, '%d / %d / %d' % (tc.get('nonempty', 0), tc.get('empty', 0), sum(v for k_, v in tc.items() if k_.startswith('unres'))),
                  fmt_counts(vcount(rs, ('ntu', 'verdict'))),
                  dict(Counter(r['ntu']['method'] for r in rs))))
    if 'panel' in res:
        W('')
        W('## Factorial panel (TU verdict ; NTU verdict)')
        W(row('point', 'ind/pess', 'ind/opt', 'coord/pess', 'coord/opt'))
        W(row(*['---'] * 5))
        d = defaultdict(dict)
        for r in res['panel']:
            p = r['params']
            name = '%s %s' % (r['family'], {k: x for k, x in p.items() if k != 'gn'})
            d[name]['%s/%s' % (r['mode'], r['sel'])] = '%s %+.4f ; %s' % (r['tu']['verdict'], r['tu']['eps'],
                                                                       r.get('ntu', {}).get('verdict', '-'))
        for name, cells in d.items():
            W(row(name, *[cells.get(c, '-') for c in ('ind/pess', 'ind/opt', 'coord/pess', 'coord/opt')]))
    if 'catalogue' in res:
        W('')
        W('## Catalogue')
        W(row('game', 'sel', 'TU', 'eps*', 'NTU core', 'some FMA>0'))
        W(row(*['---'] * 6))
        for g, rec in res['catalogue'].items():
            for sel in ('pess', 'opt'):
                x = rec[sel]
                W(row(g, sel, x['tu']['verdict'], '%.4f' % x['tu']['eps'], x['ntu_core'] or 'empty', x['any_fma']))
    # ---------------- cross-family checks
    W('')
    W('## Cross-family checks')
    allrecs = [r for k in ('cournot', 'pg', 'lq', 'bertrand', 'hombertrand', 'cournot_cap') for r in res.get(k, [])
               if not r.get('excluded')]
    e = [r for r in allrecs if emp(r)]
    W('- certified TU-empty family points: %d; with no coalition gaining from moving first: %d' %
      (len(e), sum(1 for r in e if not r['any_fma'])))
    W('- TU-empty points with an empty sim (gamma) core: %d (generic: sim core present for %d)' %
      (sum(1 for r in e if r.get('sim', {}).get('verdict') == 'empty'), sum(1 for r in e if 'sim' in r)))
    W('- leader >= sim on every coalition: %d of %d points' % (sum(1 for r in allrecs if r.get('leader_ge_sim')),
                                                             sum(1 for r in allrecs if 'leader_ge_sim' in r)))
    simemp = [(r['family'], r['params']) for r in allrecs if r.get('sim', {}).get('verdict') == 'empty']
    W('- empty sim cores: %d %s' % (len(simemp), simemp[:12]))
    sym = [r for r in allrecs if r['family'] in ('lq', 'bertrand', 'cournot', 'pg') and
           len(set(r['params'].get('b', r['params'].get('c', r['params'].get('theta', []))))) == 1]
    bad1 = [r['params'] for r in sym if r['all_dominance'] and emp(r)]
    bad2 = [r['params'] for r in sym if emp(r) and r['all_dominance']]
    W('- symmetric points: %d; dominance at all S but empty: %d (Lemma SMA check)' % (len(sym), len(bad1)))
    W('- symmetric empty points: %d; of which some coalition without follower dominance: %d' %
      (sum(1 for r in sym if emp(r)), sum(1 for r in sym if emp(r) and not r['all_dominance'])))
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    p = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'runs', 'core-existence-sweep.json')
    with open(p) as f:
        res = json.load(f)
    out = report(res)
    q = p.replace('.json', '.md')
    with open(q, 'w') as f:
        f.write(out)
    print(out)
