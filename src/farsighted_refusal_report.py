    open(os.path.join(ROOT, 'runs', 'farsighted-refusal.md'), 'w').write('\n'.join(lines) + '\n')
    json.dump(agg, open(os.path.join(ROOT, 'runs', 'farsighted-refusal.json'), 'w'), indent=1, default=R.DR._js)
    print('\n'.join(lines))


