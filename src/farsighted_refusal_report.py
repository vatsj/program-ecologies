    A('g1 freezing set: %d outcomes (all but %s); g1-x: %d outcomes. gV freezes exactly the members.' % (
        len(S['g1_freezing']['g1']), ', '.join(sorted(set(F.LAB) - set(S['g1_freezing']['g1']))) or 'none',
        len(S['g1_freezing']['g1x'])))
    if 'unequal_program' in S:
        A('Unequal-absorbing program (frozen choice for M-gKR-unequal): δ = %s, absorbing %s.' % (
            S['unequal_program']['delta'], ', '.join(S['unequal_program']['absorbing'])))
    else:
        A('No listed fixed point absorbs on an unequal pair: M-gKR-unequal not run.')
    A('')
    agg['static'] = {dk: dict(complete=r['complete'], n=r['n_fixed_points'], orbits=r['n_orbits'], weak=r['n_weak'],
                              default_absorbing=r['default']['describe']['absorbing'],
                              default_is_V=r['default']['describe']['absorbing_is_V'],
                              default_statV=r['default']['describe']['stationary_V_from_seed'])
                     for dk, r in S['deltas'].items()}
