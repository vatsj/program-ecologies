    A('')
    A('| δ | subtrees complete | core fixed points | S₃-invariant (orbits searched) | Z₃-invariant | sampled core fixed points | sampled but missed by the capped search | cross-check starts reaching a listed fixed point |')
    A('|---|---|---|---|---|---|---|---|')
    for dk, r in S['deltas'].items():
        xs = r['crosscheck']
        A('| %s | %d / %d | %d | %d (%d) | %d (%d) | %d | %d | %d / %d (cycles %d) |' % (
            dk, sum(s['complete'] for s in r['subtrees']), len(r['subtrees']), r['core_fixed_points'],
            r['subgroup']['S3']['solutions'], r['subgroup']['S3']['n_orbits'], r['subgroup']['Z3']['solutions'],
            r['subgroup']['Z3']['n_orbits'], r['sampled_core'], r['sampled_missing_from_search'],
            sum(1 for x in xs if x['fixed']), len(xs), sum(1 for x in xs if x['fixed'] is None)))
