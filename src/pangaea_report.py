"""Report for cliques on a Pangaea: runs/pangaea.md and runs/pangaea.json from runs/pangaea/lottery_*.json.gz."""
import glob
import gzip
import json
import os
import sys
from collections import defaultdict

import numpy as np
from scipy.stats import beta, binomtest

sys.path.insert(0, os.path.dirname(__file__))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'runs', 'pangaea')
CLASSES = ['D', 'Dill', 'S', 'S-', 'PBn', 'CBo', 'BR', 'APn', 'TW', 'Eo']


def load():
    rows = []
    for p in sorted(glob.glob(os.path.join(OUT, 'lottery_*.json.gz'))):
        rows += json.load(gzip.open(p))
    by = defaultdict(list)
    for r in rows:
        by[r['cell']].append(r)
    for c in by: by[c].sort(key=lambda r: r['rep'])
    return by


def cp(k, n):
    lo = 0.0 if k == 0 else beta.ppf(0.025, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(0.975, k + 1, n - k)
    return lo, hi


def at(r, g):
    """The snapshot at generation g (or the final state if the run stopped earlier, frozen or at its horizon)."""
    s = r['snaps'].get(str(g))
    if s is not None: return s
    if r['last_gen'] <= g: return r['final']
    return None


def uo(r, g):
    s = at(r, g)
    return None if s is None else bool(s['uo'])


def frac(rs, f):
    v = [f(r) for r in rs]
    v = [x for x in v if x is not None]
    k = sum(1 for x in v if x)
    return k, len(v)


def fmt_k(k, n):
    if n == 0: return '–'
    lo, hi = cp(k, n)
    return '%d/%d [%.2f, %.2f]' % (k, n, lo, hi)


def med(v):
    v = [x for x in v if x is not None and x >= 0]
    return float(np.median(v)) if v else None


def mcnemar(a, b):
    """Exact two-sided McNemar on paired booleans: b better than a in n10, worse in n01."""
    n10 = sum(1 for x, y in zip(a, b) if (not x) and y)
    n01 = sum(1 for x, y in zip(a, b) if x and (not y))
    n = n10 + n01
    p = 1.0 if n == 0 else binomtest(n10, n, 0.5).pvalue
    return n10, n01, p


def lost(r):
    return r['final'].get('status') == 'lost' or (r['final']['pcc'] < 0.05 and r['final']['coop'] < 0.01)


def main():
    by = load()
    J = {}
    L = []
    L.append('# Cliques on a Pangaea: run report (generated by `src/pangaea_report.py`)\n')
    L.append('ε = 0 lottery statistics at finite (N, I, horizon), never π. Universal-open: the scaling classifier for '
             'I > 1, the dominant compatible network ≥ 0.95 of the population and open for I = 1. Intervals are exact '
             '(Clopper–Pearson 95%).\n')

    # ---------------------------------------------------------------- continuum
    L.append('## The continuum (S-nonself, r = 100 unless marked)\n')
    L.append('| cell | runs | seeded Q / run | uo 2,000 | uo 10,000 | global one-network ≥ 0.95 (2,000) | identity islands / run (2,000) | rival islands / run | lost | estab. median | first-uo median |')
    L.append('|---|---|---|---|---|---|---|---|---|---|---|')
    cont = {}
    order = ['pg_L_100_128_r100', 'pg_L_200_64_r100', 'pg_L_800_16_r100', 'pg_L_3200_4_r100', 'pg_L_12800_1_r100',
             'pg_L_100_64_r100', 'pg_L_400_16_r100', 'pg_L_1600_4_r100', 'pg_L_6400_1_r100',
             'pg_L_100_128_rnat', 'pg_L_800_16_rnat', 'pg_L_100_64_rnat', 'pg_L_400_16_rnat',
             'pg_prop_100_128_r100', 'pg_prop_200_64_r100', 'pg_prop_800_16_r100', 'pg_prop_3200_4_r100',
             'pg_prop_12800_1_r100', 'pg_prop_100_64_r100', 'pg_prop_400_16_r100', 'pg_prop_1600_4_r100',
             'pg_prop_6400_1_r100']
    for c in order:
        rs = by.get(c, [])
        if not rs: continue
        k2, n2 = frac(rs, lambda r: uo(r, 2000)); k10, n10 = frac(rs, lambda r: uo(r, 10000))
        kg, ng = frac(rs, lambda r: (at(r, 2000) or {}).get('universal'))
        idn = np.mean([(at(r, 2000) or {}).get('ident_isl', 0) for r in rs]) if rs[0]['I'] > 1 else None
        riv = np.mean([(at(r, 2000) or {}).get('rival_isl', 0) for r in rs]) if rs[0]['I'] > 1 else None
        nl = sum(1 for r in rs if lost(r))
        cont[c] = dict(uo2000=[k2, n2], uo10000=[k10, n10], global2000=[kg, ng], ident_isl=idn, rival_isl=riv, lost=nl,
                       estab=med([r['establish_gen'] for r in rs]), first_uo=med([r['first_uo'] for r in rs]),
                       seededQ=float(np.mean([r['meta']['seeded_Q'] for r in rs])),
                       uo2000_list=[uo(r, 2000) for r in rs], uo10000_list=[uo(r, 10000) for r in rs],
                       reps=[r['rep'] for r in rs])
        L.append('| %s | %d | %.1f | %s | %s | %s | %s | %s | %d | %s | %s |' % (
            c, len(rs), cont[c]['seededQ'], fmt_k(k2, n2), fmt_k(k10, n10), fmt_k(kg, ng),
            '–' if idn is None else '%.2f' % idn, '–' if riv is None else '%.2f' % riv, nl,
            cont[c]['estab'], cont[c]['first_uo']))
    J['continuum'] = cont

    # McNemar along each total
    L.append('\n**Monotonicity (paired exact McNemar between consecutive cells in N; n10 = runs universal only in the '
             'larger-N cell, n01 = only in the smaller).**\n')
    L.append('| pair | horizon | n10 | n01 | p |')
    L.append('|---|---|---|---|---|')
    mono = []
    for chain in (['pg_L_100_128_r100', 'pg_L_200_64_r100', 'pg_L_800_16_r100', 'pg_L_3200_4_r100', 'pg_L_12800_1_r100'],
                  ['pg_L_100_64_r100', 'pg_L_400_16_r100', 'pg_L_1600_4_r100', 'pg_L_6400_1_r100']):
        for a, b in zip(chain[:-1], chain[1:]):
            if a not in cont or b not in cont: continue
            for hz in ('2000', '10000'):
                ra = dict(zip(cont[a]['reps'], cont[a]['uo%s_list' % hz])); rb = dict(zip(cont[b]['reps'], cont[b]['uo%s_list' % hz]))
                common = sorted(set(ra) & set(rb))
                n10, n01, p = mcnemar([ra[x] for x in common], [rb[x] for x in common])
                mono.append(dict(a=a, b=b, horizon=hz, n10=n10, n01=n01, p=p))
                L.append('| %s → %s | %s | %d | %d | %.3f |' % (a, b, hz, n10, n01, p))
    J['monotonicity'] = mono

    # ---------------------------------------------------------------- Pangaea endpoints
    L.append('\n## Pangaea endpoints at 2,000 (and 10,000 where run)\n')
    L.append('| cell | runs | (a) P(C,C) ≥ 0.95 | (b) M ≥ 0.99 of certified | universal (M ≥ 0.95) | open | uo 10,000 | M share min / median | target ≥ 0.9 | target min / median | Gemini band [0.75, 0.90] | remnants: sucker / uncertified coop (median) | max identity | max Q | max AP | lost | resolved / unresolved (final) | estab. median [range] | first resolved median |')
    L.append('|' + '---|' * 20)
    pang = {}
    pcells = ['pg_L_12800_1_r100', 'pg_L_6400_1_r100', 'pg_prop_12800_1_r100', 'pg_prop_6400_1_r100',
              'pg_Cdon_12800_1_r100', 'pg_Cdon_6400_1_r100', 'pg_Cdon13_12800_1_r100', 'pg_Cdon6_6400_1_r100',
              'pg_H_12800_1_r100', 'pg_L_100_128_r100_ff200', 'pg_L_100_128_r100_ff1000']
    for c in pcells:
        rs = by.get(c, [])
        if not rs: continue
        s2 = [at(r, 2000) for r in rs]
        ka = sum(1 for s in s2 if s['pcc'] >= 0.95); kb = sum(1 for s in s2 if s['M_of_cert'] >= 0.99)
        ku = sum(1 for s in s2 if s['universal']); ko = sum(1 for s in s2 if s['universal_open'])
        k10, n10 = frac(rs, lambda r: uo(r, 10000))
        Ms = [s['M'] for s in s2]; tg = [s['target'] for s in s2]
        kt = sum(1 for x in tg if x >= 0.9); kg = sum(1 for x in tg if 0.75 <= x <= 0.90)
        st = [r['final'].get('status') for r in rs]
        est = [r['establish_gen'] for r in rs]
        pang[c] = dict(n=len(rs), a=ka, b=kb, universal=ku, uo=ko, uo10000=[k10, n10], M=Ms, target=tg,
                       target_ge09=kt, gemini_band=kg, sucker=[s['sucker'] for s in s2], unc=[s['uncert_coop'] for s in s2],
                       max_ident=[r['max_ident'] for r in rs], max_Q=[r['max_Q'] for r in rs],
                       max_Q_spelling=[r['max_Q_spelling'] for r in rs], max_AP=[r['max_AP'] for r in rs],
                       lost=sum(1 for r in rs if lost(r)), status=st, estab=est,
                       first_resolved=[r['first_resolved'] for r in rs], h_sp=[s['h_sp'] for s in s2],
                       open=[s['h_open'] for s in s2], ident2000=[s['ident'] for s in s2])
        L.append('| %s | %d | %d | %d | %d | %d | %s | %.3f / %.3f | %d | %.3f / %.3f | %d | %.4f / %.4f | %.4f | %.4f | %.3f | %d | %d / %d | %s [%d, %d] | %s |' % (
            c, len(rs), ka, kb, ku, ko, fmt_k(k10, n10), min(Ms), float(np.median(Ms)), kt, min(tg), float(np.median(tg)),
            kg, float(np.median(pang[c]['sucker'])), float(np.median(pang[c]['unc'])), max(pang[c]['max_ident']),
            max(pang[c]['max_Q']), max(pang[c]['max_AP']), pang[c]['lost'], st.count('resolved'), st.count('unresolved'),
            med(est), min(est), max(est), med(pang[c]['first_resolved'])))
    J['pangaea'] = pang

    # trajectories (median over runs) for the S-nonself Pangaeas
    L.append('\n## Pangaea trajectories (S-nonself, median over runs; class shares by founder spelling class)\n')
    traj = {}
    for c in ('pg_L_12800_1_r100', 'pg_L_6400_1_r100', 'pg_H_12800_1_r100', 'pg_Cdon_12800_1_r100'):
        rs = by.get(c, [])
        if not rs: continue
        L.append('**%s**\n' % c)
        L.append('| g | P(C,C) | M | target | identity | Q | AP | sucker | certified of capable | ' + ' | '.join(CLASSES) + ' |')
        L.append('|' + '---|' * (9 + len(CLASSES)))
        tj = []
        for g in (10, 20, 30, 50, 80, 100, 150, 200, 300, 500, 1000, 2000, 10000):
            pts = [t for r in rs for t in r['trace'] if t['g'] == g]
            if not pts: continue
            m = lambda k: float(np.median([t[k] for t in pts if t.get(k) is not None]))
            cl = [float(np.median([t['cls'][j] for t in pts])) for j in range(len(CLASSES))] if 'cls' in pts[0] else None
            row = dict(g=g, pcc=m('pcc'), M=m('M'), target=m('target'), ident=m('ident'), Q=m('Q'), AP=m('AP'),
                       sucker=m('sucker'), ccap=m('ccap'), cls=cl)
            tj.append(row)
            L.append('| %d | %.3f | %.3f | %.3f | %.4f | %.4f | %.4f | %.3f | %.3f | %s |' % (
                g, row['pcc'], row['M'], row['target'], row['ident'], row['Q'], row['AP'], row['sucker'], row['ccap'],
                ' | '.join('–' if cl is None else '%.3f' % x for x in (cl or [None] * len(CLASSES)))))
        traj[c] = tj
        L.append('')
    J['trajectories'] = traj

    # ---------------------------------------------------------------- native vs constant production
    L.append('\n## Production: native r = N/2 against r = 100\n')
    L.append('| cell | r | uo 2,000 | uo 10,000 | C attempts / program / gen (to 200) | C successes / program (to 200) | D successes / program (to 200) | certified of capable at establishment (median) | estab. median |')
    L.append('|---|---|---|---|---|---|---|---|---|')
    prod = {}
    for base in ('pg_L_100_128', 'pg_L_800_16', 'pg_L_100_64', 'pg_L_400_16', 'pg_L_200_64', 'pg_L_12800_1'):
        for arm in ('r100', 'rnat'):
            c = base + '_' + arm
            rs = by.get(c, [])
            if not rs: continue
            T = rs[0]['T']
            ca = [r['ctr_at'].get('200', [0] * 7) for r in rs]
            cat = float(np.mean([x[1] for x in ca])) / (T * 200.0)
            cok = float(np.mean([x[2] for x in ca])) / T
            dok = float(np.mean([x[4] for x in ca])) / T
            cov = med([(r['estab_dec'] or {}).get('cert_of_capable') for r in rs])
            prod[c] = dict(r=rs[0]['r'], uo2000=cont.get(c, {}).get('uo2000'), uo10000=cont.get(c, {}).get('uo10000'),
                           C_att_per_prog_gen=cat, C_ok_per_prog=cok, D_ok_per_prog=dok, cov_estab=cov,
                           estab=med([r['establish_gen'] for r in rs]))
            L.append('| %s | %d | %s | %s | %.2f | %.3f | %.3f | %s | %s |' % (
                c, rs[0]['r'], fmt_k(*cont[c]['uo2000']) if c in cont else '–', fmt_k(*cont[c]['uo10000']) if c in cont else '–',
                cat, cok, dok, '–' if cov is None else '%.3f' % cov, prod[c]['estab']))
    J['production'] = prod
    # paired native comparisons
    L.append('\n| native pair | horizon | n10 (native only) | n01 (r = 100 only) | p |')
    L.append('|---|---|---|---|---|')
    natp = []
    for base in ('pg_L_100_128', 'pg_L_800_16', 'pg_L_100_64', 'pg_L_400_16'):
        a, b = base + '_r100', base + '_rnat'
        if a not in cont or b not in cont: continue
        for hz in ('2000', '10000'):
            ra = dict(zip(cont[a]['reps'], cont[a]['uo%s_list' % hz])); rb = dict(zip(cont[b]['reps'], cont[b]['uo%s_list' % hz]))
            common = sorted(set(ra) & set(rb))
            n10, n01, p = mcnemar([ra[x] for x in common], [rb[x] for x in common])
            natp.append(dict(pair=base, horizon=hz, n10=n10, n01=n01, p=p))
            L.append('| %s | %s | %d | %d | %.3f |' % (base, hz, n10, n01, p))
    J['native_pairs'] = natp

    # proportional vs S-nonself paired
    L.append('\n## Proportional control against S-nonself (paired)\n')
    L.append('| geometry | horizon | prop only | S-nonself only | p | gain |')
    L.append('|---|---|---|---|---|---|')
    pp = []
    for g_ in ('100_128', '200_64', '800_16', '3200_4', '12800_1', '100_64', '400_16', '1600_4', '6400_1'):
        a, b = 'pg_L_%s_r100' % g_, 'pg_prop_%s_r100' % g_
        if a not in cont or b not in cont: continue
        for hz in ('2000', '10000'):
            ra = dict(zip(cont[a]['reps'], cont[a]['uo%s_list' % hz])); rb = dict(zip(cont[b]['reps'], cont[b]['uo%s_list' % hz]))
            common = sorted(x for x in set(ra) & set(rb) if ra[x] is not None and rb[x] is not None)
            if not common: continue
            n10, n01, p = mcnemar([ra[x] for x in common], [rb[x] for x in common])
            pp.append(dict(geom=g_, horizon=hz, n10=n10, n01=n01, p=p, gain=(n10 - n01) / len(common)))
            L.append('| %s | %s | %d | %d | %.3f | %+.2f |' % (g_, hz, n10, n01, p, (n10 - n01) / len(common)))
    J['prop_pairs'] = pp

    # ---------------------------------------------------------------- identity establishment per copy
    L.append('\n## Identity islands and per-copy establishment (S-nonself, r = 100, 2,000)\n')
    L.append('| cell | seeded Q copies (total) | identity islands (total) | per seeded copy | runs with any identity island | islands with ≥ 1 seeded copy | identity islands among them |')
    L.append('|---|---|---|---|---|---|---|')
    pc = {}
    for c in order[:9]:
        rs = by.get(c, [])
        if not rs or rs[0]['I'] == 1: continue
        nq = sum(r['meta']['seeded_Q'] for r in rs)
        ni = 0; nany = 0; occ = 0; occ_id = 0
        for r in rs:
            s = at(r, 2000)
            fail = s['isl']['fail']; held = s['isl']['held']
            idc = [f == 'identity' for f in fail]
            ni += sum(idc); nany += int(any(idc))
            qi = r['meta']['Q_isl']
            occ += sum(1 for q in qi if q > 0)
            occ_id += sum(1 for q, f in zip(qi, idc) if q > 0 and f)
        pc[c] = dict(seeded=nq, ident_isl=ni, per_copy=ni / max(1, nq), runs_any=nany, occ=occ, occ_ident=occ_id)
        L.append('| %s | %d | %d | %.3f | %d/%d | %d | %d |' % (c, nq, ni, ni / max(1, nq), nany, len(rs), occ, occ_id))
    J['per_copy'] = pc

    # ---------------------------------------------------------------- extinctions
    L.append('\n## Early extinctions (S-nonself Pangaeas and fission–fusion)\n')
    L.append('| cell | R spellings seeded / run | R extinct by 200 (frac) | R alive at end (frac) | Q lineages seeded / run | Q max copies (median of run maxima) | Q extinct by 500 (frac) | BR seeded / run | BR extinct by 200 (frac) |')
    L.append('|---|---|---|---|---|---|---|---|---|')
    ex = {}
    for c in ('pg_L_12800_1_r100', 'pg_L_6400_1_r100', 'pg_prop_12800_1_r100', 'pg_H_12800_1_r100',
              'pg_L_100_128_r100_ff200', 'pg_L_200_64_r100', 'pg_L_800_16_r100', 'pg_L_3200_4_r100'):
        rs = by.get(c, [])
        if not rs: continue
        Rn = [len(r['ext_log']['R']['extinct']) for r in rs]
        Rx200 = [sum(1 for e in r['ext_log']['R']['extinct'] if 0 <= e <= 200) for r in rs]
        Ralive = [sum(1 for e in r['ext_log']['R']['extinct'] if e < 0) for r in rs]
        Qn = [len(r['ext_log']['Q']['extinct']) for r in rs]
        Qmax = [max(r['ext_log']['Q']['max']) if r['ext_log']['Q']['max'] else 0 for r in rs]
        Qx = [sum(1 for e in r['ext_log']['Q']['extinct'] if 0 <= e <= 500) for r in rs]
        Bn = [r['ext_log']['BR_summary']['n_seeded'] for r in rs]
        Bx = [r['ext_log']['BR_summary']['extinct_by_200'] for r in rs]
        ex[c] = dict(R=sum(Rn), R_ext200=sum(Rx200), R_alive=sum(Ralive), Q=sum(Qn), Qmax=Qmax, Q_ext500=sum(Qx),
                     BR=sum(Bn), BR_ext200=sum(Bx))
        L.append('| %s | %.1f | %.2f | %.2f | %.1f | %.0f | %.2f | %.1f | %.2f |' % (
            c, np.mean(Rn), sum(Rx200) / max(1, sum(Rn)), sum(Ralive) / max(1, sum(Rn)), np.mean(Qn),
            float(np.median(Qmax)), sum(Qx) / max(1, sum(Qn)), np.mean(Bn), sum(Bx) / max(1, sum(Bn))))
    J['extinctions'] = ex

    # ---------------------------------------------------------------- costs
    L.append('\n## Costs\n')
    L.append('| cell | runs | wall s / run (median) | max | total worker-h |')
    L.append('|---|---|---|---|---|')
    cost = {}
    tot = 0.0
    for c in sorted(by):
        t = [r['time_s'] for r in by[c]]
        tot += sum(t)
        cost[c] = dict(median=float(np.median(t)), max=float(max(t)), total_h=sum(t) / 3600)
        L.append('| %s | %d | %.0f | %.0f | %.2f |' % (c, len(t), np.median(t), max(t), sum(t) / 3600))
    L.append('\nTotal %.1f worker-hours.' % (tot / 3600))
    J['costs'] = cost
    open(os.path.join(ROOT, 'runs', 'pangaea.md'), 'w').write('\n'.join(L) + '\n')
    json.dump(J, open(os.path.join(ROOT, 'runs', 'pangaea.json'), 'w'), indent=1, default=float)
    print('\n'.join(L))


if __name__ == '__main__':
    main()
