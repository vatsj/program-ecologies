@njit(cache=True)
def _actc(J, s, c, m1, m2):
    """local action of slot s playing class c against the other two slots' classes m1, m2 (ascending slot order)."""
    if s == 0:
        return J[c, m1, m2] // 81
    if s == 1:
        return (J[m1, c, m2] // 9) % 9
    return J[m1, m2, c] % 9


@njit(cache=True)
def _plur(pcount, ppres, pnpres, i, s):
    best = -1; arg = 0
    for t in range(pnpres[i, s]):
        pc = ppres[i, s, t]
        if pcount[i, s, pc] > best:
            best = pcount[i, s, pc]; arg = pc
    return arg


@njit(cache=True)
def _upd(pcount, ppres, pnpres, tdesc, fate, lastmod, modcls, modal_g, i, N):
    """generation-boundary registers of island i: last modal outcome, plurality class per slot, and the majority
    outcome of tracked novel arrivals."""
    lastmod[i] = modal_g
    for s in range(3):
        modcls[i, s] = _plur(pcount, ppres, pnpres, i, s)
        for t in range(pnpres[i, s]):
            pc = ppres[i, s, t]
            if tdesc[i, s, pc] > 0 and 2 * pcount[i, s, pc] > N:
                d_ = tdesc[i, s, pc] - 1
                fate[d_ // 4, (d_ // 2) % 2, d_ % 2, 1] += 1
                tdesc[i, s, pc] = -tdesc[i, s, pc]


@njit(cache=True)
def _veto(fr, mig, i, s, pv, pc, lastmod, modcls, EXCL, ISMEM, J, PARTNER):
    """True if the birth (child class pc replacing victim class pv in slot s of island i) is discarded."""
    if pv == pc:
        return False
    mo = lastmod[i]
    if not ISMEM[mo]:
        return False
    if s == 0:
        m1 = modcls[i, 1]; m2 = modcls[i, 2]
    elif s == 1:
        m1 = modcls[i, 0]; m2 = modcls[i, 2]
    else:
        m1 = modcls[i, 0]; m2 = modcls[i, 1]
    a0 = _actc(J, s, pv, m1, m2); a1 = _actc(J, s, pc, m1, m2)
    if s == EXCL[mo]:
        md = fr[0]
        if md == 1 or (md == 2 and not mig) or (md == 3 and mig):
            if a0 != a1:
                return True
    else:
        md = fr[1]
        if md == 1 or (md == 2 and not mig) or (md == 3 and mig):
            if PARTNER[s, a0] != PARTNER[s, a1]:
                return True
    if fr[2] == 1 and mig and a0 != a1:
        return True
    return False


@njit(cache=True)
def _desc(fr, mig, i, s, pc, lastmod, modcls, EXCL, ISMEM, J, PARTNER):
    """descriptor 1 + 4 origin + 2 role + match of a novel arrival (0 if the island is not on a fair pair)."""
    mo = lastmod[i]
    if not ISMEM[mo]:
        return 0
    if s == 0:
        m1 = modcls[i, 1]; m2 = modcls[i, 2]
    elif s == 1:
        m1 = modcls[i, 0]; m2 = modcls[i, 2]
    else:
        m1 = modcls[i, 0]; m2 = modcls[i, 1]
    a1 = _actc(J, s, pc, m1, m2); a0 = _actc(J, s, modcls[i, s], m1, m2)
    role = 0 if s == EXCL[mo] else 1
    return 1 + (4 if mig else 0) + 2 * role + (1 if a1 == a0 else 0)


