def classify_pair(d, ga, gb):
    """Static type of a separated pair (global class indices): A-network membership, the rival and its type."""
    V = d['V'].astype(bool)
    a0, a1 = d['src_cls'](FB), d['src_cls'](FB1)
    inA = [bool(x in (a0, a1) or (V[x, a0] and V[a0, x] and V[x, a1] and V[a1, x])) for x in (ga, gb)]
    rv = scr(d['arm'])
    out = dict(inA=inA)
    cand = [x for x, ia in zip((ga, gb), inA) if not ia and x in rv]
    if any(inA) and cand:
        r = rv[cand[0]]
        out.update(kind='A-rival', rival=r['name'], rival_bridgeless=r['n_bridges'] == 0, rival_pstar=r['pstar_family'],
                   rival_hard=bool(r['n_bridges'] == 0 and r['n_mediators'] == 0 and not r['A_faked']), rival_mu=r['mu'],
                   rival_sources=[lang().rep[c] for c in d['members'][cand[0]]][:6], rival_g=int(cand[0]))
    elif any(x in rv for x in (ga, gb)):
        out.update(kind='rival-vs-nonA', rival=d['names'][[x for x in (ga, gb) if x in rv][0]])
    else:
        out.update(kind='non-A')
    return out


