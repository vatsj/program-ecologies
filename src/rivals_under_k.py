# Kernel: rival_islands._kern unchanged (exact skipping, exact lumping, ancestry labels, strong-holder log), with the
# arm's class table.  PD, w = 0.3, eps = 0, complete island graph, generation = I*N births, horizon 1e5.
# Seeds are drawn at the source level (iid canonical programs from the length prior at n = 8) and lumped by the arm's
# classes, so the same rep gives the same programs in every arm (paired seeds; runs are still the independent units).
# Forced founders replace one uniformly chosen seed individual on each forced island (N kept).  A tracked lineage is a
# duplicate column of its class carrying tag 1 (tags have no dynamic effect; lumping never merges different tags), so
# the forced founders' descendants are followed exactly, separately from natural copies of the same class.
SALT = 20261008
GENS = 100000
EXPS = ('cal', 'nat', 'pos', 'pstar', 'dctl', 'iid', 'bl', 'cont', 'time')
PRESETS = ('iid', 'dense', 'sparse')
CALIB = os.path.join(RUNS, 'rivals-under-k-calib.json')
POSCTRL = 'and(BOX(THEM(ME)),BOXD1(THEM(^D)))'    # the heaviest bridged rival of A under K at b = 16 (static screen)


def chash(x):
    return 0 if x is None else zlib.crc32(x.encode()) % 100003


def seeds(exp, N, I, mN, rep, forced, preset):
    """rs: the initial seed (depends on N, I, rep only: shared by arms, mN, presets and m = 0 references);
    rs2: the founder placement; ss: the kernel stream (independent of the arm and of the horizon, so a longer horizon
    continues a run)."""
    pc = PRESETS.index(preset)
    rs = [SALT, N, I, rep]
    rs2 = [SALT + 1, N, I, rep, chash(forced), pc]
    ex = 'nat' if exp == 'cont' else exp
    ss = (1000003 * rep + 7919 * EXPS.index(ex) + 104729 * pc + 13 * N + 17 * I + int(round(mN * 1000))
          + 31 * chash(forced) + SALT) % (2 ** 31 - 1)
    return rs, rs2, ss


def build_init(d, N, I, forced, preset, rs, rs2):
    """Canonical iid seed, lumped by the arm's classes; forced founders by replacement of one uniformly chosen seed
    individual per forced island.  Returns init over classes and the per-island founder count (0/1)."""
    L = lang()
    mu_c = L.mu_canon / L.mu_canon.sum()
    rng = np.random.default_rng(rs)
    Kc = len(mu_c); K = len(d['names'])
    initc = np.zeros((I, Kc), np.int64)
    for i in range(I):
        initc[i] = rng.multinomial(N, mu_c)
    fmask = np.zeros(I, np.int64)
    if forced is not None and preset != 'iid':
        rng2 = np.random.default_rng(rs2)
        for i in range(I):
            if preset == 'dense' or (preset == 'sparse' and i < I // 4):
                u = rng2.integers(N)
                c = int(np.searchsorted(np.cumsum(initc[i]), u, side='right'))
                initc[i, c] -= 1
                fmask[i] = 1
    init = np.zeros((I, K), np.int64)
    for i in range(I):
        np.add.at(init[i], d['cls_of'], initc[i])
    return init, fmask


def a_ref(d, R):
    a0, a1 = d['src_cls'](FB), d['src_cls'](FB1)
    V = d['V']
    return a1 if (V[R, a1] == 0 and V[a1, R] == 0) else a0


def restrict(d, init, fmask, fcls, mode, A=None, B=None):
    """Support (with an appended duplicate column for a tracked lineage), payoffs, flags, tags, initial counts.
    mode: 'none' (tags 0), 'track' (tag 1 on the duplicate only), 'pair' (rival_islands tags for (A, B); the forced
    copies are added to their own class)."""
    import rival_islands as R_
    tot = init.sum(0)
    sup = set(int(x) for x in np.nonzero(tot > 0)[0])
    if mode == 'pair' and fcls is not None:
        sup.add(int(fcls))
    for x in (A, B):
        if x is not None:
            sup.add(int(x))
    sup = sorted(sup)
    ext = list(sup)
    if mode == 'track':
        ext.append(int(fcls))
    ext = np.array(ext, np.int64)
    Vs = d['V'][np.ix_(ext, ext)].astype(np.int64)
    U = np.ascontiguousarray(PDP[Vs, Vs.T])
    PCC = np.ascontiguousarray((Vs * Vs.T).astype(float))
    coop = d['coop'][ext].copy()
    if mode == 'pair':
        tag = R_.tags_for(d, np.array(sup, np.int64), A, B)
    else:
        tag = np.zeros(len(ext), np.int64)
        if mode == 'track':
            tag[-1] = 1
    li = np.zeros((init.shape[0], len(ext)), np.int64)
    li[:, :len(sup)] = init[:, sup]
    if fcls is not None:
        if mode == 'track':
            li[:, -1] = fmask
        elif mode == 'pair':
            li[:, sup.index(int(fcls))] += fmask
    return ext, U, PCC, coop, tag, np.ascontiguousarray(li)


def sep_intervals(trace):
    """Separation episodes from the kernel's per-check generic separation flag (col 8)."""
    g = trace[:, 0]; f = trace[:, 8] > 0.5
    if not f.any():
        return dict(ever=False, n_episodes=0, first=-1, last_sep=-1, resolved_at=-1, sep_at_end=False, sep_checks=0)
    on = np.nonzero(f)[0]
    episodes = int(1 + np.sum(np.diff(on) > 1))
    last = int(on[-1])
    sep_end = bool(f[-1])
    return dict(ever=True, n_episodes=episodes, first=int(g[on[0]]), last_sep=int(g[last]),
                resolved_at=-1 if sep_end else int(g[last + 1]), sep_at_end=sep_end, sep_checks=int(f.sum()))


