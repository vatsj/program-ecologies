def fixk(N, k, uqq, uqa, uaq, uaa):
    import rival_islands as R
    return R.fix_k(N, W, k, uqq, uqa, uaq, uaa)


def rho_pair(N, vq, vx):
    """One-migrant fixation of a self-cooperator q into all-x (x self-cooperating) given q's play vq against x and
    x's play vx against q (the kernel's law)."""
    return fixk(N, 1, 0.0, PDP[vq, vx], PDP[vx, vq], 0.0)


def pstar_family(d, k):
    return any(PSTAR_RE.match(lang().rep[c]) for c in d['members'][k])


def bfs(adj, sources):
    dist = -np.ones(adj.shape[0], np.int64); dq = deque()
    for s in sources:
        dist[s] = 0; dq.append(s)
    while dq:
        u = dq.popleft()
        for v in np.nonzero(adj[u] & (dist < 0))[0]:
            dist[v] = dist[u] + 1; dq.append(v)
    return dist


def components(adj):
    n = adj.shape[0]; comp = -np.ones(n, np.int64); c = 0
    for s in range(n):
        if comp[s] >= 0: continue
        comp[s] = c; st = [s]
        while st:
            u = st.pop()
            for v in np.nonzero(adj[u] & (comp < 0))[0]:
                comp[v] = c; st.append(v)
        c += 1
    return comp, c


def screen(arm, light=False, Ns=(200, 400), refs=(FB, FB1)):
    d = arm_table(arm)
    V = d['V'].astype(bool); K = V.shape[0]
    mu, raw, nm = d['mu'], d['raw'], d['names']
    a0, a1 = d['src_cls'](refs[0]), d['src_cls'](refs[1])
    coop, est = d['coop_s'], d['est_s']
    MC = lambda x: V[x, :] & V[:, x]
    MD = lambda x: ~V[x, :] & ~V[:, x]
    notA = np.ones(K, bool); notA[[a0, a1]] = False
    netA = coop & MC(a0) & MC(a1)
    md0, md1 = MD(a0), MD(a1)
    riv = est & (md0 | md1); full = est & md0 & md1
    R_ = np.nonzero(riv)[0]; R_ = R_[np.argsort(-mu[R_])]
    # establisher graph (establishers and A) and cooperative graph
    E = np.nonzero(est | ~notA)[0]
    posE = -np.ones(K, np.int64); posE[E] = np.arange(len(E))
    adjE = V[np.ix_(E, E)] & V[np.ix_(E, E)].T
    np.fill_diagonal(adjE, False)
    distE = bfs(adjE, [posE[a0], posE[a1]])
    Cc = np.nonzero(coop | ~notA)[0]
    posC = -np.ones(K, np.int64); posC[Cc] = np.arange(len(Cc))
    adjC = V[np.ix_(Cc, Cc)] & V[np.ix_(Cc, Cc)].T
    np.fill_diagonal(adjC, False)
    distC = bfs(adjC, [posC[a0], posC[a1]])
    rows = []; union_br = np.zeros(K, bool)
    for r in R_:
        br = netA & MC(r) & notA
        union_br |= br
        bi = np.nonzero(br)[0]
        hb = int(bi[np.argmax(mu[bi])]) if len(bi) else -1
        medm = coop & notA & ~br & V[a0, :] & V[a1, :] & V[r, :]; medm[r] = False
        mi = np.nonzero(medm)[0]
        afaked = [bool(V[r, a] and not V[a, r]) for a in (a0, a1)]
        row = dict(name=nm[r], cls=int(r), mu=float(mu[r]), raw=float(raw[r]), full=bool(full[r]),
                   md=[bool(md0[r]), bool(md1[r])], pstar_family=bool(pstar_family(d, r)),
                   n_members=len(d['members'][r]),
                   n_bridges=int(br.sum()), bridge_mass=float(mu[br].sum()), bridge_raw=float(raw[br].sum()),
                   heaviest_bridge=nm[hb] if hb >= 0 else None, heaviest_bridge_mu=float(mu[hb]) if hb >= 0 else 0.0,
                   safe_bridge_mass=float(mu[br & est].sum()),
                   n_mediators=int(len(mi)), mediator_mass=float(mu[mi].sum()),
                   A_faked=bool(any(afaked)), A_faked_by=afaked,
                   path_est=int(distE[posE[r]]) if distE[posE[r]] >= 0 else None,
                   path_coop=int(distC[posC[r]]) if distC[posC[r]] >= 0 else None)
        if not light:
            prey = V[:, r] & ~V[r, :]
            row['prey_netA_mass'] = float(mu[prey & netA].sum())
            row['prey_netA_top'] = [(nm[x], float(mu[x])) for x in sorted(np.nonzero(prey & netA)[0], key=lambda x: -mu[x])[:3]]
            row['bridges_top'] = [(nm[x], float(mu[x])) for x in sorted(bi, key=lambda x: -mu[x])[:3]]
            row['mediator_top'] = [(nm[x], float(mu[x])) for x in sorted(mi, key=lambda x: -mu[x])[:3]]
            fx = {}
            for N in Ns:
                tr = []
                for j, a in enumerate((a0, a1)):
                    if not (md0, md1)[j][r]:
                        continue
                    into_a = rho_pair(N, int(V[r, a]), int(V[a, r]))
                    into_r = rho_pair(N, int(V[a, r]), int(V[r, a]))
                    tr += [into_a, into_r]
                cat = 'zero' if all(x == 0.0 for x in tr) else ('below' if max(tr) < 1e-12 else 'positive')
                fx[str(N)] = dict(rho=tr, cat=cat)
            row['fix'] = fx
        rows.append(row)
    if not light:
        for row in rows:
            r = row['cls']; prey = V[:, r] & ~V[r, :]
            row['prey_bridges_mass'] = float(mu[prey & union_br].sum())
    tot = float(mu[R_].sum()); totr = float(raw[R_].sum())

    def share(sel):
        m = float(sum(x['mu'] for x in rows if sel(x))); mr = float(sum(x['raw'] for x in rows if sel(x)))
        return dict(n=int(sum(1 for x in rows if sel(x))), mu=m, raw=mr, share=m / tot if tot else None)
    agg = dict(
        direct_bridgeless=share(lambda x: x['n_bridges'] == 0),
        hard_bridgeless=share(lambda x: x['n_bridges'] == 0 and x['n_mediators'] == 0 and not x['A_faked']),
        no_mediator_path=share(lambda x: x['path_est'] is None or x['path_est'] > 3),
        no_mediator_path_coop=share(lambda x: x['path_coop'] is None or x['path_coop'] > 3),
        A_faked=share(lambda x: x['A_faked']),
        pstar_family=share(lambda x: x['pstar_family']),
        pstar_family_bridgeless=share(lambda x: x['pstar_family'] and x['n_bridges'] == 0),
        full=share(lambda x: x['full']), half=share(lambda x: not x['full']))
    if not light:
        for N in Ns:
            for c in ('zero', 'below', 'positive'):
                agg['fix%s_%s' % (N, c)] = share(lambda x, c=c, N=N: x['fix'][str(N)]['cat'] == c)
    out = dict(arm=arm, K=K, n_canon=int(len(d['cls_of'])), n_rivals=len(rows), n_full=int(full.sum()),
               rival_mu=tot, rival_raw=totr, est_mu=float(mu[est].sum()), est_n=int(est.sum()),
               coop_n=int(coop.sum()), netA_mu=float(mu[netA].sum()), union_bridge_mu=float(mu[union_br].sum()),
               allc_row_classes=int(d['allc_row'].sum()), A=[nm[a0], nm[a1]],
               A_selfcoop=[bool(V[a0, a0]), bool(V[a1, a1])], A_mutual=bool(V[a0, a1] and V[a1, a0]),
               agg=agg, rivals=rows)
    if not light:
        comp, nc = components(adjE)
        cA = comp[posE[a0]]
        sizes = Counter(comp.tolist())
        out['graph_est'] = dict(nodes=int(len(E)), components=int(nc),
                                largest=[int(s) for _, s in sizes.most_common(5)],
                                A_component_nodes=int(sizes[cA]),
                                A_component_mu=float(mu[E[comp == cA]].sum()), est_mu=float(mu[E].sum()),
                                A_connected_to_each_other=bool(comp[posE[a0]] == comp[posE[a1]]),
                                path_hist_count={str(k): int(v) for k, v in Counter(distE.tolist()).items()},
                                path_hist_mu={str(k): float(mu[E[distE == k]].sum()) for k in sorted(set(distE.tolist()))})
        compC, ncC = components(adjC)
        sizesC = Counter(compC.tolist())
        out['graph_coop'] = dict(nodes=int(len(Cc)), components=int(ncC), largest=[int(s) for _, s in sizesC.most_common(5)],
                                 path_hist_count={str(k): int(v) for k, v in Counter(distC.tolist()).items()})
        # incompatible establisher pairs (mutual defection) not involving A, by mass
        Ve = V[np.ix_(E, E)]
        DD = ~Ve & ~Ve.T; np.fill_diagonal(DD, False)
        iu = np.argwhere(np.triu(DD, 1))
        pm = mu[E[iu[:, 0]]] * mu[E[iu[:, 1]]] if len(iu) else np.zeros(0)
        out['md_pairs'] = dict(n=int(len(iu)), mass=float(pm.sum()),
                               top=[(nm[E[iu[k, 0]]], nm[E[iu[k, 1]]], float(pm[k])) for k in np.argsort(-pm)[:10]])
    return out


def new_rivals(arm, ref='free'):
    """Sources (canonical programs) that are rivals of A under `arm` and not under `ref`, and the reverse."""
    L = lang()
    S = {a: screen(a, light=True) for a in (arm, ref)}
    D = {a: arm_table(a) for a in (arm, ref)}
    rv = {a: {r['cls']: r for r in S[a]['rivals']} for a in (arm, ref)}
    is_r = {a: np.array([int(D[a]['cls_of'][c]) in rv[a] for c in range(len(L.rep))]) for a in (arm, ref)}
    raw = L.mu_canon; Z = raw.sum()
    out = {}
    for key, sel in (('new', is_r[arm] & ~is_r[ref]), ('lost', is_r[ref] & ~is_r[arm]), ('kept', is_r[arm] & is_r[ref])):
        src = np.nonzero(sel)[0]
        items = []
        for c in sorted(src, key=lambda c: -raw[c]):
            ka = int(D[arm]['cls_of'][c]); kr = int(D[ref]['cls_of'][c])
            ra = rv[arm].get(ka); rr = rv[ref].get(kr)
            items.append(dict(src=L.rep[c], raw=float(raw[c]), cut=float(raw[c] / Z),
                              bridgeless_arm=(ra['n_bridges'] == 0) if ra else None,
                              hard_arm=(ra['n_bridges'] == 0 and ra['n_mediators'] == 0 and not ra['A_faked']) if ra else None,
                              bridgeless_ref=(rr['n_bridges'] == 0) if rr else None,
                              pstar=bool(PSTAR_RE.match(L.rep[c])),
                              class_arm=D[arm]['names'][ka], class_ref=D[ref]['names'][kr]))
        out[key] = dict(n=len(items), raw=float(raw[src].sum()), cut=float(raw[src].sum() / Z),
                        bridgeless_cut=float(sum(x['cut'] for x in items if x['bridgeless_arm'])),
                        hard_cut=float(sum(x['cut'] for x in items if x['hard_arm'])),
                        items=items[:60])
    return out


