_D = {}


def arm_table(arm):
    """Class data for an arm: V (class play matrix, uint8), mu (cut), raw, names, idx, cls_of (canon -> class),
    members, flags.  Compatible with rival_islands.restrict / tags_for."""
    if arm in _D:
        return _D[arm]
    L = lang(); v = canon_val(arm)
    Kc = v.shape[0]
    sig = defaultdict(list)
    for c in range(Kc):
        sig[(v[c].tobytes(), v[:, c].tobytes())].append(c)
    reps = []
    for mem in sig.values():
        rep = min(mem, key=lambda c: (L.bits_canon[c], c))
        reps.append((rep, mem, float(L.mu_canon[mem].sum())))
    reps.sort(key=lambda t: -t[2])
    idx = np.array([t[0] for t in reps], np.int64)
    V = np.ascontiguousarray(v[np.ix_(idx, idx)]).astype(np.uint8)
    raw = np.array([t[2] for t in reps])
    names = [L.rep[c] for c in idx]
    cls_of = np.full(Kc, -1, np.int64)
    for j, t in enumerate(reps):
        cls_of[np.array(t[1])] = j
    K = len(names)
    selfc = np.diagonal(V).astype(bool).copy()
    canon_idx = {s: i for i, s in enumerate(L.rep)}
    iC = int(cls_of[canon_idx['C']]); iD = int(cls_of[canon_idx['D']])
    allc_row = V.all(1).astype(bool)
    allc_k = np.zeros(K, bool); allc_k[iC] = True
    vD = V[:, iD].astype(bool)
    d = dict(arm=arm, n=NCUT, V=V, raw=raw, mu=raw / raw.sum(), names=names, idx={x: i for i, x in enumerate(names)},
             reps=idx, cls_of=cls_of, members=[t[1] for t in reps], canon_idx=canon_idx, iC=iC, iD=iD, selfc=selfc,
             allc_row=allc_row,
             # static flags (bridgeless_rivals): cooperative = self-cooperating, row not all-C
             coop_s=selfc & ~allc_row, est_s=selfc & ~vD & ~allc_row,
             # kernel flags (rival_islands.cls): cooperative = self-cooperating, not the class of C
             coop=selfc & ~allc_k, est=selfc & ~vD & ~allc_k)
    d['src_cls'] = lambda s: int(cls_of[canon_idx[s]])
    _D[arm] = d
    return d


def lumping_check(arm, nsample=1000, seed=7):
    """(i) every class has identical directed rows and columns for all its members (exhaustive, bytewise);
    (ii) source masses and seed probabilities preserved; (iii) establishment, rival and bridge tests agree between
    the lumped and the source-level tables on a sample of sources (all 610 when nsample >= 610)."""
    L = lang(); v = canon_val(arm); d = arm_table(arm)
    Kc = v.shape[0]
    bad_rows = 0
    for k, mem in enumerate(d['members']):
        r0 = d['reps'][k]
        for c in mem:
            if not (np.array_equal(v[c], v[r0]) and np.array_equal(v[:, c], v[:, r0])):
                bad_rows += 1
    # masses and seed probabilities: class probability = sum of member probabilities
    mu_c = L.mu_canon / L.mu_canon.sum()
    agg = np.zeros(len(d['names'])); np.add.at(agg, d['cls_of'], mu_c)
    mass_err = float(np.abs(agg - d['mu']).max())
    raw_err = float(abs(d['raw'].sum() - L.mu_canon.sum()))
    # seed law: one island of N = 200 drawn at source level and lumped versus drawn at class level (same law);
    # checked by comparing first moments over 2,000 draws each
    rng = np.random.default_rng(seed)
    a = np.zeros(len(agg)); b = np.zeros(len(agg))
    for _ in range(2000):
        x = rng.multinomial(200, mu_c); y = np.zeros(len(agg)); np.add.at(y, d['cls_of'], x); a += y
        b += rng.multinomial(200, d['mu'])
    seed_z = float(np.max(np.abs(a - b) / np.sqrt(np.maximum(a + b, 1))))
    # source-level tests
    vb = v.astype(bool)
    selfc = np.diagonal(vb).copy(); allc = vb.all(1)
    iDc = d['canon_idx']['D']
    coop = selfc & ~allc; est = coop & ~vb[:, iDc]
    f0, f1 = d['canon_idx'][FB], d['canon_idx'][FB1]
    MC = lambda x: vb[x, :] & vb[:, x]
    MD = lambda x: ~vb[x, :] & ~vb[:, x]
    rival = est & (MD(f0) | MD(f1))
    notA = np.ones(Kc, bool)
    notA[(d['cls_of'] == d['cls_of'][f0]) | (d['cls_of'] == d['cls_of'][f1])] = False
    src = np.arange(Kc) if nsample >= Kc else rng.choice(Kc, nsample, replace=False)
    S = screen(arm, light=True)
    rv = {r['cls']: r for r in S['rivals']}
    mism = Counter()
    for s in src:
        k = int(d['cls_of'][s])
        if bool(est[s]) != bool(d['est_s'][k]): mism['est'] += 1
        if bool(rival[s]) != (k in rv): mism['rival'] += 1
        if rival[s]:
            br = coop & notA & MC(f0) & MC(f1) & MC(s)
            bm = float(mu_c[br].sum())
            if (bm > 0) != (rv[k]['n_bridges'] > 0): mism['bridge'] += 1
            if abs(bm - rv[k]['bridge_mass']) > 1e-12: mism['bridge_mass'] += 1
    return dict(arm=arm, n_classes=len(d['names']), n_canon=Kc, members_bad=bad_rows, mass_err=mass_err,
                raw_err=raw_err, seed_moment_max_z=seed_z, sources_tested=int(len(src)), mismatches=dict(mism),
                ok=bool(bad_rows == 0 and mass_err < 1e-12 and not mism))


def free_reproduction():
    """The free class table built here must equal the existing n = 8 free class table (modal.build(8), the table
    almost_all_seeds.arm_data('modal', 8) / seeds_in_n use): classes, names, order, payoffs, masses."""
    import modal as M
    Lm, val, worlds, prov = M.build(NCUT)
    d = arm_table('free')
    U = PDP[d['V'].astype(int), d['V'].T.astype(int)]
    same_names = list(prov.names) == d['names']
    mu_p = np.array([c[2] for c in prov.classes])
    out = dict(n_classes_here=len(d['names']), n_classes_modal=len(prov.names), names_equal=bool(same_names),
               canon_val_equal=bool((val.astype(np.int8) == _L['free']).all()))
    if same_names:
        out['U_equal'] = bool(np.array_equal(U, prov.Ufull)); out['mu_maxdiff'] = float(np.abs(mu_p - d['mu']).max())
    else:
        pos = {x: i for i, x in enumerate(prov.names)}
        common = [x for x in d['names'] if x in pos]
        out['common'] = len(common)
    out['ok'] = bool(same_names and out.get('U_equal') and out.get('mu_maxdiff', 1) < 1e-12 and out['canon_val_equal'])
    return out


