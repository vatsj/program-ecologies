def calib_main(a):
    rows = load('cal')
    out = dict(T_nuc={}, dist={}, p={}, mN_boundary={}, n_nuc={}, x=0.3, N=200, I=16, runs={})
    for arm in ('free', 'K16', 'K4'):
        rs = [r for r in rows if r['arm'] == arm]
        if not rs: continue
        ts = np.array([t for r in rs for t in r['t_est'] if t >= 0], float)
        nis = sum(r['I'] for r in rs)
        T = float(np.median(ts))
        out['runs'][arm] = len(rs)
        out['T_nuc'][arm] = T; out['n_nuc'][arm] = [int(len(ts)), int(nis)]; out['p'][arm] = float(len(ts) / nis)
        out['dist'][arm] = {str(q): float(np.percentile(ts, q)) for q in (5, 10, 25, 50, 75, 90, 95)}
        out['mN_boundary'][arm] = round(0.3 * 200 / T, 3)
        rng = np.random.default_rng(1)
        per = [np.array([t for t in r['t_est'] if t >= 0]) for r in rs]
        bs = []
        for _ in range(2000):
            idx = rng.integers(0, len(per), len(per))
            v = np.concatenate([per[i] for i in idx])
            if len(v): bs.append(np.median(v))
        out['dist'][arm]['median_ci'] = [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]
    json.dump(out, open(CALIB, 'w'), indent=1)
    print(json.dumps(out, indent=1))


def cont_main(a):
    """(e): every natural run separated at the horizon and unresolved, continued to 3e5 generations from the same
    seeds (the kernel stream and the check schedule up to 1e5 are identical, so this extends the same trajectory;
    checked on the 1e5 check row)."""
    from multiprocessing import Pool
    nat = load('nat') + load('nat4')
    todo = [r for r in nat if r['n_sep_end'] > 0 and r['status'] == 'unresolved']
    rows = load('cont'); done = {(r['arm'], r['mN'], r['rep']) for r in rows}
    jobs = [('cont', r['arm'], r['N'], r['I'], r['mN'], r['rep'], 300000, None, 'iid') for r in todo
            if (r['arm'], r['mN'], r['rep']) not in done]
    if a.maxreps < len(jobs):
        jobs = jobs[:a.maxreps]
    print('cont: %d jobs' % len(jobs), flush=True)
    orig = {(r['arm'], r['mN'], r['rep']): r for r in todo}
    with Pool(a.procs, initializer=warm) as pool:
        for r in pool.imap_unordered(job, jobs):
            o = orig[(r['arm'], r['mN'], r['rep'])]
            r['matches_1e5'] = bool(r['trace_1e5'] is not None and np.allclose(r['trace_1e5'], o['final_trace']))
            rows.append(r); save('cont', rows)
            print('cont %s mN=%g rep %d: %s gen %d sep_end %d (was %d) matches %s (%.0fs)' % (
                r['arm'], r['mN'], r['rep'], r['status'], r['stop_gen'], r['n_sep_end'], o['n_sep_end'], r['matches_1e5'],
                r['time_s']), flush=True)


